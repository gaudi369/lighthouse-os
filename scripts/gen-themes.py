# (foreground, background, minimum ratio, why)
CONTRAST_RULES = [
    ("on_surface", "surface", 7.0, "body text (WCAG AAA)"),
    ("on_surface_variant", "surface_variant", 4.5, "secondary text (AA)"),
    ("on_primary", "primary", 4.5, "text on primary buttons (AA)"),
    ("on_secondary", "secondary", 4.5, "text on secondary (AA)"),
    ("on_tertiary", "tertiary", 4.5, "text on tertiary (AA)"),
    ("on_error", "error", 4.5, "text on errors (AA)"),
    ("primary", "surface", 3.0, "focus ring and icons vs background (1.4.11)"),
    ("outline", "surface", 3.0, "borders vs background (1.4.11)"),
]


# --- colour helpers ----------------------------------------------------------

def rgb(hex_):
    h = hex_.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexc(c):
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(v))) for v in c)


def mix(a, b, t):
    return hexc(tuple(x + (y - x) * t for x, y in zip(rgb(a), rgb(b))))


def luminance(hex_):
    def chan(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (chan(v) for v in rgb(hex_))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def contrast_problems(theme):
    c = theme["colors"]
    return [f"{fg} on {bg}: {contrast(c[fg], c[bg]):.2f} < {need} ({why})"
            for fg, bg, need, why in CONTRAST_RULES if contrast(c[fg], c[bg]) < need]


# --- outputs -------------------------------------------------------------------

def noctalia_palette(theme):
    c = theme["colors"]
    dark = theme["mode"] == "dark"
    variant = {
        "mPrimary": c["primary"], "mOnPrimary": c["on_primary"],
        "mSecondary": c["secondary"], "mOnSecondary": c["on_secondary"],
        "mTertiary": c["tertiary"], "mOnTertiary": c["on_tertiary"],
        "mError": c["error"], "mOnError": c["on_error"],
        "mSurface": c["surface"], "mOnSurface": c["on_surface"],
        "mSurfaceVariant": c["surface_variant"], "mOnSurfaceVariant": c["on_surface_variant"],
        "mOutline": c["outline"],
        "mShadow": "#000000" if dark else mix(c["surface"], "#000000", 0.25),
        "mHover": mix(c["surface_variant"], c["primary"], 0.18),
        "mOnHover": c["on_surface"],
    }
    # Each theme is one mode; give Noctalia the same colours for both variants.
    return {"dark": variant, "light": variant}


def niri_kdl(theme):
    c = theme["colors"]
    return f"""// Generated by scripts/gen-themes.py from themes/{theme['id']}.toml
layout {{
    focus-ring {{
        active-color "{c['primary']}"
        inactive-color "{c['outline']}"
    }}
}}
"""


def noctalia_toml(theme):
    return f"""# Generated by scripts/gen-themes.py from themes/{theme['id']}.toml
[theme]
mode           = "{theme['mode']}"
source         = "custom"
custom_palette = "{theme['id']}"

[wallpaper.default]
path = "/usr/share/lighthouse/themes/{theme['id']}/wallpaper.svg"
"""


def theme_json(theme):
    return {k: theme[k] for k in ("id", "name", "mode", "description")} | {"colors": theme["colors"]}


