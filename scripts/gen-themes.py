# Original scenes inspired by the settings of A. A. Milne's books (1926/1928).
# Drawn from simple shapes; no character likenesses.

W, H = 1920, 1080


def hill(y, amp, waves, phase, color, opacity=1):
    pts = [f"{x},{y + amp * math.sin(x / W * waves * 2 * math.pi + phase):.1f}"
           for x in range(0, W + 40, 40)]
    return f'<path d="M0,{H} L{" L".join(pts)} L{W},{H} Z" fill="{color}" opacity="{opacity}"/>'


def ground_y(y, amp, waves, phase, x):
    return y + amp * math.sin(x / W * waves * 2 * math.pi + phase)


def cloud(x, y, s, color, opacity=0.9):
    puffs = [(0, 0, 60), (55, -25, 50), (110, 0, 55), (55, 15, 55), (-45, 12, 40), (155, 15, 38)]
    circles = "".join(f'<circle cx="{x + dx * s:.0f}" cy="{y + dy * s:.0f}" r="{r * s:.0f}"/>'
                      for dx, dy, r in puffs)
    return f'<g fill="{color}" opacity="{opacity}">{circles}</g>'


def stars(n, seed, color, y_max=700, r_max=3.2):
    rnd = random.Random(seed)
    out = []
    for _ in range(n):
        x, y, r = rnd.uniform(0, W), rnd.uniform(70, y_max), rnd.uniform(1.2, r_max)
        out.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{r:.1f}" fill="{color}" '
                   f'opacity="{rnd.uniform(0.5, 1):.2f}"/>')
    return "".join(out)


def sun(x, y, r, color, rays=True):
    out = [f'<circle cx="{x}" cy="{y}" r="{r}" fill="{color}"/>']
    if rays:
        for i in range(12):
            a = i / 12 * 2 * math.pi
            x1, y1 = x + math.cos(a) * r * 1.3, y + math.sin(a) * r * 1.3
            x2, y2 = x + math.cos(a) * r * 1.65, y + math.sin(a) * r * 1.65
            out.append(f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y2:.0f}" '
                       f'stroke="{color}" stroke-width="{r * 0.16:.0f}" stroke-linecap="round"/>')
    return "".join(out)


def tree(x, base, h, trunk, crown, crown2=None):
    crown2 = crown2 or crown
    tw = h * 0.14
    return (f'<rect x="{x - tw / 2:.0f}" y="{base - h * 0.55:.0f}" width="{tw:.0f}" '
            f'height="{h * 0.6:.0f}" rx="{tw * 0.3:.0f}" fill="{trunk}"/>'
            f'<circle cx="{x:.0f}" cy="{base - h * 0.7:.0f}" r="{h * 0.3:.0f}" fill="{crown}"/>'
            f'<circle cx="{x - h * 0.25:.0f}" cy="{base - h * 0.55:.0f}" r="{h * 0.22:.0f}" fill="{crown2}"/>'
            f'<circle cx="{x + h * 0.25:.0f}" cy="{base - h * 0.58:.0f}" r="{h * 0.24:.0f}" fill="{crown2}"/>')


def balloon(x, y, r, color):
    return (f'<path d="M{x},{y + r * 1.15} q{-r * 0.3},{r * 0.8} {r * 0.1},{r * 1.6} '
            f't{-r * 0.2},{r * 1.4}" stroke="#44515E" stroke-width="3" fill="none"/>'
            f'<ellipse cx="{x}" cy="{y}" rx="{r}" ry="{r * 1.15}" fill="{color}"/>'
            f'<path d="M{x - 10},{y + r * 1.13} l10,14 l10,-14 Z" fill="{color}"/>'
            f'<ellipse cx="{x - r * 0.35}" cy="{y - r * 0.4}" rx="{r * 0.2}" ry="{r * 0.32}" '
            f'fill="#FFFFFF" opacity="0.45" transform="rotate(-25 {x - r * 0.35} {y - r * 0.4})"/>')


def honey_pot(x, base, s, pot, label, text_color):
    w, h = 170 * s, 190 * s
    top = base - h
    return (f'<path d="M{x - w * 0.42},{top + h * 0.14} C{x - w * 0.62},{top + h * 0.45} '
            f'{x - w * 0.6},{base - h * 0.05} {x - w * 0.3},{base} L{x + w * 0.3},{base} '
            f'C{x + w * 0.6},{base - h * 0.05} {x + w * 0.62},{top + h * 0.45} {x + w * 0.42},{top + h * 0.14} Z" '
            f'fill="{pot}"/>'
            f'<rect x="{x - w * 0.46:.0f}" y="{top:.0f}" width="{w * 0.92:.0f}" height="{h * 0.16:.0f}" '
            f'rx="{h * 0.06:.0f}" fill="{mix(pot, "#000000", 0.25)}"/>'
            f'<path d="M{x - w * 0.2},{top + h * 0.16} q0,{h * 0.22} {w * 0.07},{h * 0.22} '
            f'q{w * 0.07},0 {w * 0.07},{-h * 0.22} Z" fill="{mix(pot, "#FFD000", 0.5)}"/>'
            f'<rect x="{x - w * 0.34:.0f}" y="{top + h * 0.45:.0f}" width="{w * 0.68:.0f}" '
            f'height="{h * 0.26:.0f}" rx="8" fill="{label}"/>'
            f'<text x="{x:.0f}" y="{top + h * 0.64:.0f}" text-anchor="middle" '
            f'font-family="Noto Sans, sans-serif" font-weight="800" font-size="{h * 0.15:.0f}" '
            f'fill="{text_color}">HUNNY</text>')


def thistle(x, base, h, stem, flower):
    return (f'<path d="M{x},{base} C{x - 8},{base - h * 0.4} {x + 8},{base - h * 0.7} {x},{base - h}" '
            f'stroke="{stem}" stroke-width="7" fill="none" stroke-linecap="round"/>'
            f'<path d="M{x},{base - h * 0.45} q-45,-10 -60,-45 q30,5 60,25 Z" fill="{stem}"/>'
            f'<path d="M{x},{base - h * 0.65} q45,-10 60,-45 q-30,5 -60,25 Z" fill="{stem}"/>'
            f'<ellipse cx="{x}" cy="{base - h - 14}" rx="22" ry="26" fill="{mix(stem, "#FFFFFF", 0.15)}"/>'
            + "".join(f'<line x1="{x}" y1="{base - h - 30}" x2="{x + dx}" y2="{base - h - 72}" '
                      f'stroke="{flower}" stroke-width="7" stroke-linecap="round"/>'
                      for dx in (-26, -13, 0, 13, 26)))


def stick_house(x, base, s, color):
    sticks = []
    for i in range(9):
        t = i / 8
        sticks.append(f'<line x1="{x - 150 * s + t * 300 * s:.0f}" y1="{base}" '
                      f'x2="{x + (t - 0.5) * 40 * s:.0f}" y2="{base - 200 * s:.0f}" '
                      f'stroke="{color}" stroke-width="{9 * s:.0f}" stroke-linecap="round"/>')
    return "".join(sticks)


def rain(seed, color, n=160):
    rnd = random.Random(seed)
    return "".join(
        f'<line x1="{x:.0f}" y1="{y:.0f}" x2="{x - 10:.0f}" y2="{y + 34:.0f}" stroke="{color}" '
        f'stroke-width="3" stroke-linecap="round" opacity="0.45"/>'
        for x, y in ((rnd.uniform(0, W + 60), rnd.uniform(80, 900)) for _ in range(n)))


def acorn(x, y, s, nut, cap):
    return (f'<ellipse cx="{x}" cy="{y + 14 * s:.0f}" rx="{16 * s:.0f}" ry="{21 * s:.0f}" fill="{nut}"/>'
            f'<path d="M{x - 20 * s:.0f},{y + 2 * s:.0f} q{20 * s:.0f},{-26 * s:.0f} {40 * s:.0f},0 Z" fill="{cap}"/>'
            f'<line x1="{x}" y1="{y - 10 * s:.0f}" x2="{x + 4 * s:.0f}" y2="{y - 18 * s:.0f}" '
            f'stroke="{cap}" stroke-width="{4 * s:.0f}" stroke-linecap="round"/>')


def flower(x, y, r, petal, center):
    petals = "".join(f'<circle cx="{x + math.cos(a) * r:.0f}" cy="{y + math.sin(a) * r:.0f}" r="{r * 0.75:.0f}"/>'
                     for a in (i / 5 * 2 * math.pi - math.pi / 2 for i in range(5)))
    return f'<g fill="{petal}">{petals}</g><circle cx="{x}" cy="{y}" r="{r * 0.55:.0f}" fill="{center}"/>'


def carrot(x, base, s, orange, green):
    return (f'<path d="M{x - 18 * s:.0f},{base - 10 * s:.0f} L{x + 18 * s:.0f},{base - 10 * s:.0f} '
            f'L{x},{base + 55 * s:.0f} Z" fill="{orange}"/>'
            + "".join(f'<path d="M{x},{base - 8 * s:.0f} q{dx * s:.0f},{-40 * s:.0f} {dx * 1.6 * s:.0f},{-58 * s:.0f}" '
                      f'stroke="{green}" stroke-width="{7 * s:.0f}" fill="none" stroke-linecap="round"/>'
                      for dx in (-12, 0, 12)))


def fence(y, color):
    posts = "".join(f'<path d="M{x},{y} l0,-95 l14,-18 l14,18 l0,95 Z" fill="{color}"/>'
                    for x in range(0, W + 40, 52))
    return (posts + f'<rect x="0" y="{y - 75}" width="{W}" height="12" fill="{mix(color, "#000000", 0.12)}"/>'
            f'<rect x="0" y="{y - 35}" width="{W}" height="12" fill="{mix(color, "#000000", 0.12)}"/>')


def hop_trail(x0, y0, hops, length, height, color, width, dash):
    d = f"M{x0},{y0}"
    for _ in range(hops):
        d += f" q{length / 2},{-height} {length},0"
    return (f'<path d="{d}" stroke="{color}" stroke-width="{width}" fill="none" '
            f'stroke-dasharray="{dash}" stroke-linecap="round"/>')


def sign(x, y, text, board, ink, size=30):
    w = len(text) * size * 0.62 + 30
    return (f'<rect x="{x - 6}" y="{y}" width="12" height="130" fill="{mix(board, "#000000", 0.3)}"/>'
            f'<rect x="{x - w / 2:.0f}" y="{y - size * 0.4:.0f}" width="{w:.0f}" height="{size * 1.6:.0f}" '
            f'rx="6" fill="{board}" transform="rotate(-4 {x} {y})"/>'
            f'<text x="{x}" y="{y + size * 0.72:.0f}" text-anchor="middle" font-family="Noto Sans, sans-serif" '
            f'font-weight="700" font-size="{size}" fill="{ink}" transform="rotate(-4 {x} {y})">{text}</text>')


