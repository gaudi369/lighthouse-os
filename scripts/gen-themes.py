def load_themes():
    themes = []
    for path in sorted((ROOT / "themes").glob("*.toml")):
        theme = tomllib.loads(path.read_text())
        theme["id"] = path.stem
        themes.append(theme)
    return themes


def install_current(out, theme_id):
    """What `lighthouse-theme set` does, applied to the rootfs tree."""
    src = out / "usr/share/lighthouse/themes" / theme_id
    current = out / "etc/lighthouse/theme"
    current.mkdir(parents=True, exist_ok=True)
    for name in ("theme.json", "palette.json", "niri.kdl"):
        shutil.copy(src / name, current / name)
    shutil.copy(src / "noctalia.toml", out / "etc/lighthouse/noctalia/theme.toml")


def generate(out):
    problems = []
    for theme in load_themes():
        if theme["id"] not in SCENES:
            problems.append(f"{theme['id']}: no wallpaper scene")
            continue
        problems += [f"{theme['id']}: {p}" for p in contrast_problems(theme)]
        d = out / "usr/share/lighthouse/themes" / theme["id"]
        d.mkdir(parents=True, exist_ok=True)
        palette = json.dumps(noctalia_palette(theme), indent=2) + "\n"
        (d / "palette.json").write_text(palette)
        (d / "theme.json").write_text(json.dumps(theme_json(theme), indent=2) + "\n")
        (d / "niri.kdl").write_text(niri_kdl(theme))
        (d / "noctalia.toml").write_text(noctalia_toml(theme))
        (d / "wallpaper.svg").write_text(wallpaper_svg(theme))
        palettes = out / "etc/lighthouse/noctalia/palettes"
        palettes.mkdir(parents=True, exist_ok=True)
        (palettes / f"{theme['id']}.json").write_text(palette)
    install_current(out, DEFAULT_THEME)
    return problems


GENERATED = ["usr/share/lighthouse/themes", "etc/lighthouse/noctalia/palettes",
             "etc/lighthouse/theme", "etc/lighthouse/noctalia/theme.toml"]


def main():
    check = "--check" in sys.argv
    rootfs = ROOT / "rootfs"
    if check:
        with tempfile.TemporaryDirectory() as tmp:
            problems = generate(Path(tmp))
            for rel in GENERATED:
                a, b = Path(tmp) / rel, rootfs / rel
                files_a = sorted(p.relative_to(a) for p in a.rglob("*") if p.is_file()) if a.is_dir() else None
                files_b = sorted(p.relative_to(b) for p in b.rglob("*") if p.is_file()) if b.is_dir() else None
                same = (files_a == files_b and all((a / f).read_bytes() == (b / f).read_bytes() for f in files_a)
                        if a.is_dir() else b.is_file() and a.read_bytes() == b.read_bytes())
                if not same:
                    problems.append(f"rootfs/{rel} is stale; run scripts/gen-themes.py")
    else:
        problems = generate(rootfs)

    for theme in load_themes():
        c = theme["colors"]
        print(f"{theme['id']:<20} {theme['mode']:<5}  text {contrast(c['on_surface'], c['surface']):5.2f}  "
              f"primary {contrast(c['primary'], c['surface']):4.2f}  "
              f"on-primary {contrast(c['on_primary'], c['primary']):4.2f}")
    if problems:
        print("\n".join(["", "Problems:"] + [f"  {p}" for p in problems]))
        sys.exit(1)


if __name__ == "__main__":
    main()
